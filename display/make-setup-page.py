#!/usr/bin/env python3
"""Rebuild the copy of setup-page.html that the firmware carries.

The board serves its Wi-Fi setup page from a gzip-compressed array compiled into the
firmware (components/captive_portal/captive_index.h). Run this after editing
setup-page.html, and commit both files. `--check` only reports whether they match.
"""
import gzip
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, "setup-page.html")
TARGET = os.path.join(HERE, "components", "captive_portal", "captive_index.h")


def build():
    with open(SOURCE, "rb") as f:
        page = f.read()
    packed = gzip.compress(page, 9, mtime=0)            # mtime=0: same input, same output
    rows = [", ".join("0x%02x" % b for b in packed[i:i + 16]) for i in range(0, len(packed), 16)]
    return ("#pragma once\n"
            "// Generated by display/make-setup-page.py from display/setup-page.html. Do not edit.\n\n"
            '#include "esphome/core/hal.h"\n\n'
            "namespace esphome::captive_portal {\n\n"
            "#ifndef USE_CAPTIVE_PORTAL_GZIP\n"
            '#error "This page is only built gzip-compressed: leave captive_portal compression at gzip."\n'
            "#endif\n\n"
            "constexpr uint8_t INDEX_GZ[] PROGMEM = {\n    " + ",\n    ".join(rows) + ",\n};\n\n"
            "}  // namespace esphome::captive_portal\n")


if __name__ == "__main__":
    new = build()
    old = open(TARGET).read() if os.path.exists(TARGET) else ""
    if "--check" in sys.argv:
        # Compare what the header unpacks to, not its bytes: different zlib builds can
        # compress the same page to different bytes.
        try:
            body = re.search(r"INDEX_GZ\[\] PROGMEM = \{([^}]*)\}", old).group(1)
            held = gzip.decompress(bytes(int(x, 16) for x in body.replace("\n", " ").split(",") if x.strip()))
        except Exception:
            held = None
        with open(SOURCE, "rb") as f:
            sys.exit(0 if held == f.read()
                     else "captive_index.h is out of date: run display/make-setup-page.py")
    with open(TARGET, "w") as f:
        f.write(new)
    print("Wrote %s (%d bytes of page)" % (os.path.relpath(TARGET, HERE), os.path.getsize(SOURCE)))
